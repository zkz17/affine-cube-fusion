# -*- coding: utf-8 -*-
"""
Post-refactor acceptance check: re-synthesize a sample of cases with the
renamed/moved backend and compare T/CX against the committed files under
data/our_cost/ (generated by the pre-refactor code). A full match proves the
refactor preserved behavior for the production paths.
"""
from utils.TruthTable import TruthTable
from utils.to_qiskit import to_qiskit
from evaluate import count_costs
from backend.OracleSynthesizer import OracleSynthesizer


def loadv(path):
    return [int(l.split(':')[1]) for l in open(path)]


def check(tag, n, cases, samples):
    t_file = loadv(f'data/our_cost/t_cost/our_t_cost_{tag}_{n}_0_{cases}.txt')
    cx_file = loadv(f'data/our_cost/cx_cost/our_cx_cost_{tag}_{n}_0_{cases}.txt')
    fn_list = [int(l) for l in open(f'data/test_cases/test_cases_{n}').readlines()[:cases]]
    kwargs = dict(reorder=True, ancilla_num=0, fused_backend=True)
    if tag == 'A':
        kwargs['paths'] = ('A',)
    elif tag == 'C':
        kwargs['paths'] = ('C',)
    elif tag == 'FP':
        kwargs['fprm_proxy'] = True
    elif tag == 'G':
        kwargs['gl_search'] = True
    s = OracleSynthesizer(**kwargs)
    step = max(1, cases // samples)
    bad = 0
    for i in range(0, cases, step):
        tt = TruthTable(fn_list[i], n)
        s.synthesize(tt)
        t, cx = count_costs(to_qiskit(s.circ))
        if t != t_file[i] or cx != cx_file[i]:
            bad += 1
            print(f'  MISMATCH {tag} n={n} i={i}: file={t_file[i]}/{cx_file[i]}, now={t}/{cx}')
        if bad >= 5:
            break
    print(f'{tag} n={n}: {samples} sampled, {bad} mismatches')
    return bad


def main():
    plan = [('F', 4, 65536, 30), ('A', 4, 65536, 30), ('F', 5, 10000, 30),
            ('F', 6, 10000, 20), ('F', 7, 10000, 10), ('FP', 7, 10000, 10),
            ('C', 6, 10000, 10), ('G', 6, 10000, 5), ('F', 9, 1000, 10),
            ('FP', 10, 1000, 5)]
    total_bad = 0
    for tag, n, cases, samples in plan:
        total_bad += check(tag, n, cases, samples)
    print('TOTAL mismatches:', total_bad)
    assert total_bad == 0, 'refactor changed behavior on sampled cases!'


if __name__ == '__main__':
    main()
